#!/usr/bin/env python3
"""迁移漂移**降级感知**断言（自包含：内部运行 ``alembic check`` 并按三态判定）。

依据（H-1：不改设计；本脚本只修**断言口径**）
--------------------------------------------
多处 CI/nightly 断言以「裸 ``alembic check`` 零漂移」为准，隐含前提是**标准档（带 vector
扩展）**。但在 **plain ``postgres:16``**（无 ``vector`` 扩展、无 pgvector 包）下，0013/0014
迁移走**设计内降级路径**：``CREATE EXTENSION vector`` 失败 → WARNING → 向量列型退化为
``jsonb``。于是 ``alembic check``（模型侧 ``VectorType`` vs DB 侧 ``jsonb``）**必然**报 2 项
``modify_type`` 漂移（``embedding.vector`` / ``memory.vector``，``jsonb`` → ``VectorType``）
并非零退出。原口径在该档**不成立** → 属**测试断言口径缺陷**，非产品缺陷。

标准档（pgvector）零漂移由「PostgreSQL (pgvector) migration + knowledge」job 经其
``alembic check`` **完整覆盖**；plain 档（降级形态）冒烟与回滚演练则用**本脚本**统一断言。

判定口径（严格白名单，禁假绿）
------------------------------
- ``alembic check`` rc == 0 → PASS（**标准档零漂移**，或 SQLite 等零漂移档）；
- rc != 0 且漂移明细**恰好**为已知 2 项 ``modify_type``（``embedding.vector`` 与
  ``memory.vector``，``jsonb`` → ``VectorType``）且**无任何其他** upgrade operations
  → PASS（**降级档已知差异白名单**）；
- 其余任何情形（多 1 项 / 少项 / 异项 / 解析失败 / 非漂移类非零退出）→ FAIL（打印完整原文，rc=1）。

**不可放宽**：白名单**严格恰好 2 项**；多 1 项即 fail；不得写成「含这 2 项即过」；不使用
``|| true`` / 无条件跳过。

用法
----
在线（CI，自包含）：本脚本自行调用 ``python -m alembic check``（继承当前环境变量，如
``ASTRA_DATABASE_URL`` / ``ASTRA_MODE``）并判定::

    uv run python scripts/check_migration_drift.py

离线（合成输入自测，不需 PG；**经文件**，不使用 stdin）::

    python scripts/check_migration_drift.py --rc 255 --input-file <path>
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from pathlib import Path

#: 降级档**已知且设计内**的漂移：``(表名, 列名)``，每项须为 ``modify_type``（jsonb→vector）。
KNOWN_DOWNGRADE_DIFFS: frozenset[tuple[str, str]] = frozenset(
    {("embedding", "vector"), ("memory", "vector")}
)

#: alembic 漂移明细的稳定前缀（``command.check`` 经 ``AutogenerateDiffsDetected`` 抛出）。
_DRIFT_MARKER = "New upgrade operations detected:"

#: 括号配对与闭括号集合（用于结构切分，尊重字符串字面量）。
_BRACKET_PAIRS = {"(": ")", "[": "]", "{": "}"}
_CLOSERS = frozenset(")]}")


def _skip_string(text: str, index: int) -> int:
    """``index`` 指向字符串开引号；返回**闭引号之后**的下标（正确处理 ``\\`` 转义）。"""
    quote = text[index]
    i = index + 1
    while i < len(text):
        char = text[i]
        if char == "\\":
            i += 2
            continue
        if char == quote:
            return i + 1
        i += 1
    raise ValueError("字符串字面量未闭合")


def _match_bracket(text: str, start: int) -> int:
    """``text[start]`` 为 ``([{`` 之一；返回匹配闭括号的下标（含）。"""
    stack = [_BRACKET_PAIRS[text[start]]]
    i = start + 1
    while i < len(text):
        char = text[i]
        if char in "\"'":
            i = _skip_string(text, i)
            continue
        if char in _BRACKET_PAIRS:
            stack.append(_BRACKET_PAIRS[char])
        elif char in _CLOSERS:
            if not stack or char != stack[-1]:
                raise ValueError(f"括号不匹配：{char!r} @ {i}")
            stack.pop()
            if not stack:
                return i
        i += 1
    raise ValueError("括号未闭合")


def _split_top_level(inner: str) -> list[str]:
    """按**顶层**逗号切分（尊重字符串与嵌套括号）；返回去空白后的元素文本。"""
    parts: list[str] = []
    depth = 0
    start = 0
    i = 0
    while i < len(inner):
        char = inner[i]
        if char in "\"'":
            i = _skip_string(inner, i)
            continue
        if char in _BRACKET_PAIRS:
            depth += 1
        elif char in _CLOSERS:
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(inner[start:i].strip())
            start = i + 1
        i += 1
    tail = inner[start:].strip()
    if tail:
        parts.append(tail)
    return parts


def _unquote(text: str) -> str | None:
    """若 ``text`` 为单/双引号字符串字面量 → 返回其内容；否则 ``None``。"""
    stripped = text.strip()
    if len(stripped) >= 2 and stripped[0] in "\"'" and stripped[-1] == stripped[0]:
        return stripped[1:-1]
    return None


def extract_drift_payload(output: str) -> str | None:
    """从 alembic 原文提取漂移明细的 ``[...]`` 片段（未找到 → ``None``）。"""
    marker_at = output.find(_DRIFT_MARKER)
    if marker_at < 0:
        return None
    bracket_at = output.find("[", marker_at + len(_DRIFT_MARKER))
    if bracket_at < 0:
        return None
    return output[bracket_at : _match_bracket(output, bracket_at) + 1]


def iter_operation_tuples(payload: str) -> list[str]:
    """拆出顶层每个操作元组的**文本**。

    ``alembic.check`` 的 ``diffs`` 为顶层 list，元素有两形态：① 单操作 ``tuple``（多数 op）；
    ② 单列变更的 ``list[tuple]``（``AlterColumnOp.to_diff_tuple`` 返回列表，可含
    ``modify_type`` / ``modify_nullable`` …）。两者统一展平为「操作元组」序列。
    """
    entries = _split_top_level(payload.strip()[1:-1])
    operations: list[str] = []
    for entry in entries:
        if entry.startswith("("):
            operations.append(entry)
        elif entry.startswith("["):
            for sub in _split_top_level(entry[1:-1]):
                if not sub.startswith("("):
                    raise ValueError(f"list 元素非操作元组：{sub[:60]}")
                operations.append(sub)
        else:
            raise ValueError(f"顶层元素非操作元组/列表：{entry[:60]}")
    return operations


def parse_operation(operation: str) -> tuple[str, list[str]]:
    """把 ``('kind', elem1, …)`` 解析为 ``(kind, [元素…])``。"""
    elements = _split_top_level(operation.strip()[1:-1])
    if not elements:
        raise ValueError("空操作元组")
    kind = _unquote(elements[0])
    if kind is None:
        raise ValueError(f"操作名非字符串字面量：{elements[0][:40]}")
    return kind, elements


def is_known_downgrade_drift(operations: list[tuple[str, list[str]]]) -> bool:
    """判断是否为**恰好**已知 2 项降级档漂移（严格白名单；多/少/异项一律 ``False``）。"""
    if len(operations) != len(KNOWN_DOWNGRADE_DIFFS):
        return False
    seen: set[tuple[str, str]] = set()
    for kind, elements in operations:
        # ('modify_type', schema, tname, cname, {…}, existing_type, modify_type)
        if kind != "modify_type" or len(elements) < 7:
            return False
        table = _unquote(elements[2])
        column = _unquote(elements[3])
        if table is None or column is None or (table, column) not in KNOWN_DOWNGRADE_DIFFS:
            return False
        if "JSONB" not in elements[5] or "VectorType" not in elements[6]:
            return False
        seen.add((table, column))
    return seen == set(KNOWN_DOWNGRADE_DIFFS)


def evaluate(rc: int, output: str) -> int:
    """按判定口径返回退出码：``0``=PASS / ``1``=FAIL。"""
    if rc == 0:
        print("[ci-drift] PASS：alembic check 零漂移（rc=0，标准档 / 零漂移档）。")
        return 0
    payload = extract_drift_payload(output)
    if payload is None:
        print(f"[ci-drift] FAIL：alembic check 非零退出（rc={rc}）且未见漂移明细。原文：")
        print(output)
        return 1
    try:
        operations = [parse_operation(op) for op in iter_operation_tuples(payload)]
    except ValueError as exc:
        print(f"[ci-drift] FAIL：漂移明细解析失败（{exc}）。原文：")
        print(output)
        return 1
    if is_known_downgrade_drift(operations):
        print(
            "[ci-drift] PASS：降级档已知差异（设计内，0013/0014 降级路径）"
            "——modify_type jsonb↔vector ×2（embedding.vector / memory.vector）。"
        )
        return 0
    print(f"[ci-drift] FAIL：检测到白名单之外的漂移操作（共 {len(operations)} 项）：")
    for kind, elements in operations:
        detail = ", ".join(elements[1:4])
        print(f"  - {kind}({detail})")
    print("---- alembic check 原文 ----")
    print(output)
    return 1


def _run_alembic_check() -> tuple[int, str]:
    """调用 ``python -m alembic check``（继承当前环境），返回 ``(退出码, 合并输出)``。"""
    proc = subprocess.run(
        [sys.executable, "-m", "alembic", "check"],
        capture_output=True,
        text=True,
        check=False,
    )
    return proc.returncode, f"{proc.stdout}{proc.stderr}"


def main(argv: list[str] | None = None) -> int:
    """CLI 入口。在线：自跑 ``alembic check``；离线自测：``--rc`` + ``--input-file``（文件）。"""
    parser = argparse.ArgumentParser(
        description="迁移漂移降级感知断言（严格白名单，自包含运行 alembic check）。"
    )
    parser.add_argument(
        "--rc",
        type=int,
        default=None,
        help="离线自测：直接给定 alembic check 退出码（需配 --input-file）。",
    )
    parser.add_argument(
        "--input-file", default=None, help="离线自测：从文件读取合成输出（不使用 stdin）。"
    )
    args = parser.parse_args(argv)

    if args.rc is not None or args.input_file is not None:
        if args.rc is None or args.input_file is None:
            parser.error("离线自测需同时提供 --rc 与 --input-file。")
        output = Path(args.input_file).read_text(encoding="utf-8")
        return evaluate(args.rc, output)

    rc, output = _run_alembic_check()
    sys.stdout.write(output)
    return evaluate(rc, output)


if __name__ == "__main__":
    raise SystemExit(main())
